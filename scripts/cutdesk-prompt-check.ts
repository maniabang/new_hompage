import assert from "node:assert/strict";
const { promptIssues, syncAssetPrompt, mcpHandoff } = await import(new URL("../src/lib/cutdesk/prompt.ts", import.meta.url).href);
import type { Asset, Cut } from "../src/lib/cutdesk/types";
const asset=(id:string,name:string,selected=true):Asset=>({id,name,path:`refs/${name}`,kind:"image",role:"배경",note:"공간 기준",checksum:null,selected,preview:null});
const a=asset("one","현주 시트 .png");
const dialogue="[대사]\n현주: 원문은 그대로 유지합니다.";
let text=syncAssetPrompt(dialogue,[a]);
assert.ok(text.includes("@{현주 시트 .png}"));assert.ok(text.endsWith(dialogue));
assert.equal(syncAssetPrompt(text,[a]),text,"Repeated sync is idempotent");
assert.deepEqual(promptIssues(text,[a]),[]);
assert.equal(promptIssues("@Image2",[a]).length,1,"Do not infer old numbered tags");
assert.equal(promptIssues("@{다른파일.png}",[a]).length,1);
assert.ok(promptIssues(text,[a,asset("two",a.name)]).some((x: string)=>x.includes("같은 파일명")));
assert.equal(promptIssues(text,[{...a,name:a.name.normalize("NFD")}]).length,0);
assert.equal(syncAssetPrompt(text,[]),dialogue,"Unselected managed references removed; screenplay preserved");
const b=asset("two","새 배경.png");text=syncAssetPrompt(text,[b]);assert.ok(!text.includes(a.name));assert.ok(text.includes(b.name));
assert.ok(promptIssues("@{현주 시트 .png}",[b]).length,"Body references require review, not silent reassignment");
const cut={code:"EP01_S01_C001A",title:"테스트 컷",duration:12.5,assets:[b]} as Cut;
const packet=mcpHandoff(cut,text);assert.ok(packet.includes(cut.code));assert.ok(packet.includes("Aqua_Edit/refs/새 배경.png"));assert.ok(packet.includes("등록 SHA-256: 미확인"));assert.ok(!packet.includes("Bearer"));
const excluded=mcpHandoff({...cut,chief_review:{source_revision:438,verified_revision:439,status:"제외",application:"excluded",issues:[],proposal:""}},text);assert.ok(excluded.includes("견적·생성하지 마세요"));
console.log("PASS: exact filenames, Unicode, idempotent selection sync, preserved dialogue, unresolved and duplicate references, MCP handoff and excluded cuts.");
